// scoreboard renders docs/benchmark.md.
func scoreboard(m *Manifest, r *Run) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("<!-- Generated by `go run -tags testbed ./testbed/bench`. Don't edit by hand: rerun the benchmark. -->\n\n")
	w("# Echo benchmark\n\n")
	w("The testbed (`testbed/`) is a WordPress shop, a Laravel app, a Next.js app and a plain-PHP page with %d scenarios in which a site ", len(m.Scenarios))
	w("stops saying what it should and %d in which the environment around Echo goes wrong. ", len(m.Environment))
	w("Each scenario has a good state and a broken state. For every site scenario the benchmark ")
	w("sets the good state, runs the scenario's action with `rhythm-echo snapshot --action`, breaks the scenario, runs it again with ")
	w("`rhythm-echo compare --action` and checks the comparison for the change listed in `testbed/scenarios.yaml`. ")
	w("For every environment scenario a probe sets up each state, runs Echo's commands and checks what they printed, their exit codes and their verdicts.\n\n")
	w("We wrote both Echo and the testbed, so read this as a regression suite with a scoreboard, not an independent review: ")
	w("every scenario is something we built Echo to catch. Each one is still a real failure mode, in a real WordPress, Laravel or Next.js, ")
	w("and it passes only when Echo reports the expected change through its normal commands. The other tools run on the same states, ")
	w("and anyone can rerun it all from a clean checkout (see [Run it](#run-it)).\n\n")
	switch {
	case r.BinErr != nil:
		w("**Echo wasn't run:** %s.\n\n", r.BinErr)
	default:
		w("**Echo caught %d of %d site scenarios and %d of %d environment scenarios.**", r.caught(), len(r.Outcomes), r.envCaught(), len(r.Env))
		if r.Partial {
			w(" (a partial run: `-only` was used)")
		}
		w("\n\n")
	}
	ver := r.Version
	if ver == "" {
		ver = "unknown version"
	}
	w("Run on %s with %s (%s/%s); the run took %s.\n\n", r.Started.UTC().Format("2006-01-02"), ver, runtime.GOOS, runtime.GOARCH, r.Duration.Round(time.Second))

	if len(r.Outcomes) > 0 {
		w("## Site scenarios\n\n")
		head, rule := "| # | Area | Scenario | Stack | Expected | Echo |", "|---|---|---|---|---|---|"
		for _, name := range toolNames {
			head += " " + toolTitle(name) + " |"
			rule += "---|"
		}
		w("%s\n%s\n", head, rule)
		for _, o := range r.Outcomes {
			s := o.Scenario
			var exp []string
			for _, e := range s.Expect {
				exp = append(exp, cell(e.String()))
			}
			name := s.Name
			if s.Mode == "observe" {
				name += " (observe mode)"
			}
			echo := mark(o.Echo)
			if s.Known != "" && o.Echo.Outcome != Caught {
				echo += " (known Echo issue, see Details)"
			}
			w("| %s | %s | %s | %s | %s | %s |", s.ID, areaNames[s.Area], cell(name), s.Stack, strings.Join(exp, "<br>or "), cell(echo))
			for _, name := range toolNames {
				t, ok := o.Tools[name]
				if !ok {
					w(" not run |")
					continue
				}
				w(" %s |", cell(mark(t)))
			}
			w("\n")
		}
		w("\n**caught**: the expected change was reported · found, as X: the problem was reported in another class · missed · ")
		w("can't see: outside what the tool captures · error: the tool failed (see Details) · not run: the tool wasn't available\n\n")
	}

	if len(r.Env) > 0 {
		w("## Environment scenarios\n\n")
		w("| # | Scenario | Needs | Broken state | Echo must | Echo |\n|---|---|---|---|---|---|\n")
		for _, o := range r.Env {
			s := o.Scenario
			var must []string
			for _, c := range s.Broken {
				must = append(must, cell(c.String()))
			}
			echo := mark(o.Echo)
			if s.Known != "" && o.Echo.Outcome != Caught {
				echo += " (known Echo issue, see Details)"
			}
			w("| %s | %s | %s | %s | %s | %s |\n", s.ID, cell(s.Name), s.Needs, cell(s.Toggle), strings.Join(must, "<br>"), cell(echo))
		}
		w("\n**caught**: every check of the broken state held (and the good state's held too) · missed: one didn't (see Details) · ")
		w("error: the good state failed its own checks or the probe couldn't run · not run: it needs a machine or the testbed this run didn't have\n\n")
	}

	if len(r.Outcomes) > 0 {
		w("## How the other tools are judged\n\n")
		for _, name := range toolNames {
			w("- %s", newTool(name, "", nil, options{}).About())
			if err := r.ToolErr[name]; err != nil {
				w(" Not run this time: %s.", err)
			}
			w("\n")
		}
		w("- **MessagePit** is not run: it has no published Docker image (`docker search messagepit` finds none) or release binary we could run without building it, so it has no column rather than a guess.\n\n")
	}

	w("## Details\n\n")
	for _, area := range areas {
		first := true
		for _, o := range r.Outcomes {
			s := o.Scenario
			if s.Area != area {
				continue
			}
			if first {
				w("### %s\n\n", areaNames[area])
				first = false
			}
			w("**%s %s** (%s, action “%s”, %s mode, %.0f s). Broken state: %s.\n", s.ID, s.Name, s.Stack, s.Action, s.Mode, o.Seconds, s.Toggle)
			e := o.Echo
			switch {
			case e.Found != "":
				w("Echo: %s.", e.Found)
			case e.Detail != "":
				w("Echo: %s: %s.", e.Outcome, strings.TrimSuffix(e.Detail, "."))
			default:
				w("Echo: %s.", e.Outcome)
			}
			if len(e.Others) > 0 {
				w(" Also reported: %s.", strings.Join(e.Others, "; "))
			}
			if s.Known != "" && e.Outcome != Caught {
				w("\n> **Known Echo issue:** %s", s.Known)
			}
			w("\n")
			for _, name := range toolNames {
				if t, ok := o.Tools[name]; ok && (t.Found != "" || t.Detail != "") {
					w("%s: %s.\n", toolTitle(name), strings.TrimSuffix(t.Found+t.Detail, "."))
				}
			}
			w("\n")
		}
	}
	if len(r.Env) > 0 {
		w("### Environment\n\n")
		for _, o := range r.Env {
			s := o.Scenario
			w("**%s %s** (needs %s, probe `%s`, %.0f s). Broken state: %s.\n", s.ID, s.Name, s.Needs, s.Probe, o.Seconds, s.Toggle)
			e := o.Echo
			switch {
			case e.Found != "":
				w("Echo: %s.", e.Found)
			case e.Detail != "":
				w("Echo: %s: %s.", e.Outcome, strings.TrimSuffix(e.Detail, "."))
			default:
				w("Echo: %s.", e.Outcome)
			}
			if s.Known != "" && e.Outcome != Caught {
				w("\n> **Known Echo issue:** %s", s.Known)
			}
			w("\n\n")
		}
	}

	w("## Run it\n\n")
	w("From a clean checkout, with Docker (Compose v2) and Go:\n\n")
	w("```sh\ngit clone https://github.com/RhythmShahriar/echo && cd echo\n")
	w("make -C testbed up TOOLS=\"echo mailpit buggregator staging-shield\"   # the sites on :18850-18858 (a few minutes the first time, then about 30 s)\n")
	w("make -C testbed benchmark TOOLS=\"echo mailpit buggregator staging-shield\"   # builds Echo, runs every scenario, writes docs/benchmark.md\n")
	w("make -C testbed reproduce TOOLS=\"echo mailpit buggregator staging-shield\"   # runs it twice and fails if any outcome differs\n")
	w("go run -tags testbed ./testbed/bench -only s05,e05   # some scenarios\n")
	w("go run -tags testbed ./testbed/bench -only env -tools none   # the environment scenarios; the local ones need no Docker\n")
	w("make -C testbed down\n```\n\n")
	w("The benchmark starts its own Echo (`rhythm-echo up` on 0.0.0.0:18860-18862 with the token `make up` wrote to `testbed/runtime/token`, a fresh one each time and masked here; the containers reach it through the testbed's gate) ")
	w("and a fixture DNS server on 127.0.0.1:18870 for the deliverability scenarios. ")
	w("The local environment probes run their own Echo and fixtures on 127.0.0.1:23200-23239. ")
	w("The version skew scenario builds Echo %s from its git tag, with its modules from the Go module cache or, when they aren't there, downloaded: its first run needs the network unless the cache is warm. ", oldEchoTag)
	w("Buggregator and Staging Shield are only set up with `TOOLS` naming them: Buggregator's image is pulled and Staging Shield is downloaded from wordpress.org into the WordPress image when it's built. ")
	w("Runs are kept in `testbed/bench/work/<id>/` (the snapshot, compare.json, DNS check output, each environment step's JSON); `work/results.json` has every result.\n")
	return b.String()
}

// toolTitle is a tool's column header.
func toolTitle(name string) string { return newTool(name, "", nil, options{}).Title() }

func mark(r Result) string {
	switch r.Outcome {
	case Caught:
		return "**caught**"
	case OtherClass:
		cls, _, _ := strings.Cut(r.Found, " ")
		return "found, as " + strings.ToUpper(cls)
	case Missed:
		return "missed"
	case CantSee:
		return "can't see"
	case Failed:
		return "error"
	}
	return r.Outcome
}

// cell escapes text for a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
