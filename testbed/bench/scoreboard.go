// scoreboard renders docs/benchmark.md.
func scoreboard(m *Manifest, r *Run) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("<!-- Generated by `go run -tags testbed ./testbed/bench`. Don't edit by hand: rerun the benchmark. -->\n\n")
	w("# Echo benchmark\n\n")
	w("The testbed (`testbed/`) is a WordPress shop, a Laravel app, a Next.js app and a plain-PHP page with %d scenarios in which a site ", len(m.Scenarios))
	w("stops saying what it should. Each scenario has a good state and a broken state, switched by `testbed/toggle.sh`. For every scenario the benchmark ")
	w("sets the good state, runs the scenario's action with `rhythm-echo snapshot --action`, breaks the scenario, runs it again with ")
	w("`rhythm-echo compare --action`, and checks the comparison for the change listed in `testbed/scenarios.yaml`.\n\n")
	w("We wrote both Echo and the testbed, so read this as a regression suite with a scoreboard, not an independent review: ")
	w("every scenario is something we built Echo to catch. Each one is still a real failure mode, in a real WordPress, Laravel or Next.js, ")
	w("and it passes only when Echo reports the expected change through its normal commands.\n\n")
	switch {
	case r.BinErr != nil:
		w("**Echo wasn't run:** %s.\n\n", r.BinErr)
	default:
		w("**Echo caught %d of %d scenarios.**", r.caught(), len(r.Outcomes))
		if r.Partial {
			w(" (a partial run: `-only` was used)")
		}
		w("\n\n")
	}
	ver := r.Version
	if ver == "" {
		ver = "unknown version"
	}
	w("Run on %s with %s (%s/%s); the run took %s.\n\n", r.Started.UTC().Format("2006-01-02"), ver, runtime.GOOS, runtime.GOARCH, r.Duration.Round(time.Second))

	w("| # | Area | Scenario | Stack | Expected | Echo | Mailpit | MessagePit |\n|---|---|---|---|---|---|---|---|\n")
	for _, o := range r.Outcomes {
		s := o.Scenario
		var exp []string
		for _, e := range s.Expect {
			exp = append(exp, cell(e.String()))
		}
		mp := "not run"
		if t, ok := o.Tools["mailpit"]; ok {
			mp = mark(t)
		}
		name := s.Name
		if s.Mode == "observe" {
			name += " (observe mode)"
		}
		echo := mark(o.Echo)
		if s.Known != "" && o.Echo.Outcome != Caught {
			echo += " (known Echo issue, see Details)"
		}
		w("| %s | %s | %s | %s | %s | %s | %s | not run |\n", s.ID, areaNames[s.Area], cell(name), s.Stack, strings.Join(exp, "<br>or "), cell(echo), cell(mp))
	}
	w("\n**caught**: the expected change was reported · found, as X: the problem was reported in another class · missed · ")
	w("can't see: outside what the tool captures · error: the tool failed (see Details) · not run: the tool wasn't available\n\n")

	w("## How the other tools are judged\n\n")
	w("- **Mailpit** (`axllent/mailpit:v1.29.2`) is the usual staging mail catcher: it receives mail over SMTP and shows it in an inbox. ")
	w("It has no notion of a baseline, so it can't report a change; the question here is whether a person reading the Mailpit inbox would have seen the problem. ")
	w("For each state, the benchmark delivers into the testbed's Mailpit, over SMTP, the emails Echo captured that the site would have handed to an SMTP server ")
	w("(mail sent through a provider's API, such as Resend's, never reaches an SMTP catcher), then reads them back through Mailpit's API. ")
	w("It counts as **caught** when the broken-state inbox visibly shows the problem (the scenario's `mailpit` text is in a message's From, To, Subject or body, and wasn't in the good state's). ")
	w("A message that is no longer sent is a **miss**: the inbox just has one email fewer. SMS, chat, webhooks, analytics and DNS are **can't see**.")
	if r.Mailpit != nil {
		w(" Not run this time: %s.", r.Mailpit)
	}
	w("\n- **MessagePit** is not run: it has no published Docker image (`docker search messagepit` finds none) or release binary we could run without building it, so its column says \"not run\" rather than guessing.\n\n")

	w("## Details\n\n")
	for _, area := range areas {
		first := true
		for _, o := range r.Outcomes {
			s := o.Scenario
			if s.Area != area {
				continue
			}
			if first {
				w("### %s\n\n", areaNames[area])
				first = false
			}
			w("**%s %s** (%s, action “%s”, %s mode, %.0f s). Broken state: %s.\n", s.ID, s.Name, s.Stack, s.Action, s.Mode, o.Seconds, s.Toggle)
			e := o.Echo
			switch {
			case e.Found != "":
				w("Echo: %s.", e.Found)
			case e.Detail != "":
				w("Echo: %s: %s.", e.Outcome, strings.TrimSuffix(e.Detail, "."))
			default:
				w("Echo: %s.", e.Outcome)
			}
			if len(e.Others) > 0 {
				w(" Also reported: %s.", strings.Join(e.Others, "; "))
			}
			if s.Known != "" && e.Outcome != Caught {
				w("\n> **Known Echo issue:** %s", s.Known)
			}
			w("\n")
			if t, ok := o.Tools["mailpit"]; ok && (t.Found != "" || t.Detail != "") {
				w("Mailpit: %s.\n", strings.TrimSuffix(t.Found+t.Detail, "."))
			}
			w("\n")
		}
	}

	w("## Run it\n\n")
	w("```sh\nmake build                 # bin/rhythm-echo\nmake -C testbed up         # the sites on :18850-18855 (a few minutes the first time, then about 30 s)\n")
	w("go run -tags testbed ./testbed/bench                 # Echo + Mailpit\n")
	w("go run -tags testbed ./testbed/bench -only s05,s09   # some scenarios\nmake -C testbed down\n```\n\n")
	w("The benchmark starts its own Echo (`rhythm-echo up` on 0.0.0.0:18860-18862 with the testbed's token; the containers reach it through the testbed's gate) ")
	w("and a fixture DNS server on 127.0.0.1:18870 for the deliverability scenarios. ")
	w("Runs are kept in `testbed/bench/work/<id>/` (the snapshot, compare.json, DNS check output); `work/results.json` has every result.\n")
	return b.String()
}

func mark(r Result) string {
	switch r.Outcome {
	case Caught:
		return "**caught**"
	case OtherClass:
		cls, _, _ := strings.Cut(r.Found, " ")
		return "found, as " + strings.ToUpper(cls)
	case Missed:
		return "missed"
	case CantSee:
		return "can't see"
	case Failed:
		return "error"
	}
	return r.Outcome
}

// cell escapes text for a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
