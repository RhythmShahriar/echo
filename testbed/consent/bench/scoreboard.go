// GeneratedHeader is the scoreboard's first line, as Soundcheck's.
const GeneratedHeader = "<!-- Generated by testbed/consent/bench. Don't edit by hand: rerun the benchmark. -->"

// framing is PRD 18.2's framing paragraph, with the sink count put in,
// spelled as the PRD spells it.
const framing = "Proprietary CMPs are replicas of public markup captured on the listed dates; " +
	"Google's and Meta's tags are stand-ins written to community-documented behaviour; " + //nolint:misspell // the PRD's words
	"nothing reached the internet (sink count %d, must be 0); evidence, not legal advice. " +
	"Machine, OS, Chrome, Echo version and date are listed below."

// headline is the scoreboard's first sentence.
func headline(r *Results) string {
	caught, bad := 0, 0
	for _, o := range r.Scenarios {
		if o.Scenario.Good() {
			continue
		}
		bad++
		if o.Echo.Outcome == judge.Caught {
			caught++
		}
	}
	alarms, checks := 0, 0
	for _, c := range r.Control {
		alarms += c.FalseAlarms
		checks += c.Rounds
	}
	return fmt.Sprintf("Echo caught %d of %d scenarios. False alarms: %d in %d checks of unchanged good sites.", caught, bad, alarms, checks)
}

// cell makes s safe in a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	if s == "" {
		return "-"
	}
	return s
}

// pct is ok of n as a percentage, "-" for none needed.
func pct(ok, n int) string {
	if n == 0 {
		return "-"
	}
	return fmt.Sprintf("%d of %d (%d%%)", ok, n, ok*100/n)
}

// writeScoreboard writes docs/benchmark-consent.md for r.
func writeScoreboard(w io.Writer, r *Results) error {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("%s\n\n# Echo consent benchmark\n\n", GeneratedHeader)
	p("%s\n\n", headline(r))
	p(framing+"\n\n", r.Leaks)
	p("- Echo: %s\n- Browser: %s\n- Machine: %s\n- Mode: %s\n- Date: %s, %.0f minutes\n",
		cell(r.Echo), cell(r.Browser), cell(r.Machine), r.Mode, r.Started.UTC().Format("2006-01-02 15:04 UTC"), r.Seconds/60)
	if r.Partial {
		p("- Partial run: only the scenarios picked with -only\n")
	}
	for _, e := range r.Errors {
		p("- Error: %s\n", cell(e))
	}

	p("\n## Targets\n\n| Measure | Value | Target | State |\n|---|---|---|---|\n")
	for _, m := range r.Measures {
		state := m.State
		if m.Note != "" {
			state += " (" + m.Note + ")"
		}
		p("| %s | %s | %s | %s |\n", cell(m.Name), cell(m.Value), cell(m.Target), cell(state))
	}

	p("\n## Scenarios\n\nEach bad scenario's broken state must match every expect and no forbid; its good state must be clean. ")
	p("A stand-in that didn't load makes the scenario a miss, never a catch.\n\n")
	head := []string{"ID", "Scenario", "CMP", "Echo"}
	for _, t := range r.Tools {
		head = append(head, toolNames[t])
	}
	p("| %s |\n|%s\n", strings.Join(head, " | "), strings.Repeat("---|", len(head)))
	var details []string
	for _, o := range r.Scenarios {
		row := []string{o.Scenario.ID, cell(o.Scenario.Name), o.Scenario.CMP, o.Echo.Outcome}
		for _, t := range r.Tools {
			v, ok := o.Tools[t]
			if !ok {
				v = judge.Verdict{Outcome: judge.NotRun}
			}
			row = append(row, v.Outcome)
		}
		p("| %s |\n", strings.Join(row, " | "))
		if o.Echo.Outcome != judge.Caught && o.Echo.Outcome != judge.Clean {
			details = append(details, fmt.Sprintf("- %s %s: %s", o.Scenario.ID, o.Echo.Outcome, cell(o.Echo.Detail)))
		}
		if g := o.GoodState; g != nil && g.Outcome != judge.Clean {
			details = append(details, fmt.Sprintf("- %s good state %s: %s", o.Scenario.ID, g.Outcome, cell(g.Detail)))
		}
	}
	if len(details) > 0 {
		p("\nMisses and failures, with what Echo reported:\n\n%s\n", strings.Join(details, "\n"))
	}
	if len(r.ToolNotes) > 0 {
		p("\nOther tools: ")
		var notes []string
		for _, t := range slices.Sorted(maps.Keys(r.ToolNotes)) {
			notes = append(notes, toolNames[t]+" "+r.ToolNotes[t])
		}
		p("%s. Blacklight and paid scanners are online services: not run.\n", strings.Join(notes, "; "))
	} else {
		p("\nBlacklight and paid scanners are online services: not run.\n")
	}

	p("\n## Control pass\n\nThe good state of every scenario, %d rounds. Any error or warning outside the scenario's allow list is a false alarm; ", r.Rounds)
	p("a round whose verdict differs from round 1 is a flake.\n\n| ID | Rounds | False alarms | Flakes | Failed |\n|---|---|---|---|---|\n")
	var cdetails []string
	for _, c := range r.Control {
		p("| %s | %d | %d | %d | %d |\n", c.ID, c.Rounds, c.FalseAlarms, c.Flakes, c.Failed)
		for _, d := range c.Details {
			cdetails = append(cdetails, "- "+c.ID+" "+cell(d))
		}
	}
	if len(cdetails) > 0 {
		p("\n%s\n", strings.Join(cdetails, "\n"))
	}

	p("\n## Environment probes\n\n| ID | Probe | Echo | Detail |\n|---|---|---|---|\n")
	for _, e := range r.Environment {
		d := e.Echo.Detail
		if d == "" {
			d = e.Echo.Found
		}
		p("| %s | %s | %s | %s |\n", e.Probe.ID, cell(e.Probe.Name), e.Echo.Outcome, cell(d))
	}

	p("\n## Click success per CMP\n\nVerified choices over the runs that needed one, on good states.\n\n")
	p("| CMP | Accept | Reject | %s (reference) |\n|---|---|---|---|\n", toolNames[toolAutoconsent])
	for _, c := range r.Clicks {
		p("| %s | %s | %s | %s |\n", c.CMP, pct(c.AcceptOK, c.AcceptNeeded), pct(c.RejectOK, c.RejectNeeded), cell(orNotRun(c.Reference)))
	}

	t := r.Timing
	p("\n## Timing\n\n| Measure | p50 | p95 or max | Samples |\n|---|---|---|---|\n")
	p("| Time per page (from the reports) | %.1f s | %.1f s (p95) | %d |\n", t.PageP50, t.PageP95, t.Pages)
	p("| consent detect (wall time) | %.1f s | %.1f s (max) | %d |\n", t.DetectP50, t.DetectMax, t.Detects)
	if t.RSSMax > 0 {
		p("\nPeak resident memory of rhythm-echo (Chrome excluded): %s.\n", mib(t.RSSMax))
	}

	p("\n## CMP replicas\n\n| Replica | Captured |\n|---|---|\n")
	for _, rp := range r.Replicas {
		p("| %s | %s |\n", rp.Name, rp.Captured)
	}

	p("\n## Run it\n\n```sh\n")
	p("make build\n")
	p("go run -tags testbed ./testbed/consent/bench -bin bin/rhythm-echo        # Go mode, no Docker\n")
	p("make -C testbed/consent up && make bench-consent                         # sealed Docker mode, the benchmark of record\n")
	p("make -C testbed/consent reproduce                                       # two full runs, compared with -diff\n")
	p("```\n\nOne scenario by hand: `make -C testbed/consent serve`, then ")
	p("`rhythm-echo consent https://c01.shop.test/ $(make -s -C testbed/consent map)` after `./testbed/consent/toggle.sh c01 broken`.\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// orNotRun is s, or "not run" when it is empty.
func orNotRun(s string) string {
	if s == "" {
		return judge.NotRun
	}
	return s
}

// capturedLine is a SOURCE.md's capture date.
var capturedLine = regexp.MustCompile(`(?m)^captured: (\d{4}-\d{2}-\d{2})$`)

// replicas lists every CMP replica with its capture date.
func replicas() []Replica {
	st := server.Static()
	entries, err := fs.ReadDir(st, "cmps")
	if err != nil {
		return nil
	}
	var out []Replica
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "vendor" {
			continue
		}
		src, err := fs.ReadFile(st, "cmps/"+e.Name()+"/SOURCE.md")
		if err != nil {
			continue
		}
		date := "unknown"
		if m := capturedLine.FindSubmatch(src); m != nil {
			date = string(m[1])
		}
		out = append(out, Replica{Name: e.Name(), Captured: date})
	}
	return out
}
