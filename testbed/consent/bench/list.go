package main

import (
	"fmt"
	"io"
	"strings"

	"github.com/RhythmShahriar/echo/testbed/consent/scenarios"
)

// The README's scenario tables sit between these lines; -list prints
// them and TestReadmeTableMatchesManifest compares the two.
const (
	listBegin = "<!-- Scenario tables: generated by go run -tags testbed ./testbed/consent/bench -list. Don't edit by hand. -->"
	listEnd   = "<!-- End of the generated scenario tables. -->"
)

// writeList writes m as the README's Markdown tables, framed by
// listBegin and listEnd: the bad and good scenarios, the Docker
// variants, the environment probes and the security fixtures.
func writeList(w io.Writer, m *scenarios.Manifest) {
	var b strings.Builder
	b.WriteString(listBegin + "\n\n")

	b.WriteString("### Bad scenarios\n\n")
	b.WriteString("The good state is a correct site; `toggle.sh <id> broken` switches on what the last but one column says.\n\n")
	b.WriteString("| ID | Scenario | Area | CMP | Extra flags | Broken state | Echo must find |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, s := range m.Scenarios {
		if s.Good() {
			continue
		}
		join := "; "
		if s.Any {
			join = "; or "
		}
		row(&b, s.ID, s.Name, s.Area, s.CMP, flags(s), s.Toggle, matches(s.Expect, join)+forbids(s.Forbid))
	}

	b.WriteString("\n### Good scenarios\n\n")
	b.WriteString("No error and no warning in any run; only the notices listed may appear.\n\n")
	b.WriteString("| ID | Scenario | Area | CMP | Extra flags | Notices allowed |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, s := range m.Scenarios {
		if !s.Good() {
			continue
		}
		allowed := "none"
		if len(s.Allow) > 0 {
			allowed = code(s.Allow, ", ")
		}
		row(&b, s.ID, s.Name, s.Area, s.CMP, flags(s), allowed)
	}

	b.WriteString("\n### Docker variants\n\n")
	b.WriteString("The same scenario on the real WordPress plugin, run only with `-mode docker`.\n\n")
	b.WriteString("| ID | Scenario | CMP | Site |\n|---|---|---|---|\n")
	for _, v := range m.Variants {
		row(&b, v.ID, v.Of, v.CMP, v.Site+".shop.test")
	}

	b.WriteString("\n### Environment probes\n\n")
	b.WriteString("| ID | Probe | Needs | Broken state |\n|---|---|---|---|\n")
	for _, p := range m.Environment {
		row(&b, p.ID, p.Name, p.Needs, p.Toggle)
	}

	b.WriteString("\n### Security fixtures\n\n")
	b.WriteString("| Site | What for |\n|---|---|\n")
	for _, f := range m.Fixtures {
		row(&b, f.ID, f.Use)
	}
	b.WriteString("\n" + listEnd + "\n")
	_, _ = io.WriteString(w, b.String())
}

// row writes one table row, escaping the pipes a cell may hold.
func row(b *strings.Builder, cells ...string) {
	for i, c := range cells {
		cells[i] = strings.ReplaceAll(c, "|", `\|`)
	}
	b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
}

// flags is a scenario's extra runs and arguments as one cell.
func flags(s scenarios.Scenario) string {
	var parts []string
	if len(s.Runs) > 0 {
		parts = append(parts, "`--runs "+strings.Join(s.Runs, ",")+"`")
	}
	if len(s.Args) > 0 {
		args := make([]string, len(s.Args))
		for i, a := range s.Args {
			if strings.ContainsAny(a, " ;(){}") {
				a = `"` + a + `"`
			}
			args[i] = a
		}
		parts = append(parts, "`"+strings.Join(args, " ")+"`")
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(parts, " ")
}

// matches lists expectations in code spans, joined by sep.
func matches(ms []scenarios.Match, sep string) string {
	var parts []string
	for _, m := range ms {
		parts = append(parts, m.String())
	}
	return code(parts, sep)
}

// forbids adds what a catch must not rest on, if anything.
func forbids(ms []scenarios.Match) string {
	if len(ms) == 0 {
		return ""
	}
	return "; not " + matches(ms, ", not ")
}

// code puts every item in a code span and joins them with sep.
func code(items []string, sep string) string {
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = fmt.Sprintf("`%s`", s)
	}
	return strings.Join(out, sep)
}
