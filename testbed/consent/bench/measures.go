// detectTimes runs consent detect on the good state of every scenario
// in list that has a banner and returns each wall time. A detect that
// fails or finds no banner is noted.
func (b *Bench) detectTimes(ctx context.Context, list []scenarios.Scenario) ([]time.Duration, []string) {
	var times []time.Duration
	var notes []string
	for _, s := range list {
		if s.CMP == "none" || ctx.Err() != nil {
			continue
		}
		if err := b.bed.SetBroken(s.ID, false); err != nil {
			notes = append(notes, s.ID+": "+err.Error())
			continue
		}
		rel := filepath.ToSlash(filepath.Join("detect", s.ID))
		if err := os.MkdirAll(filepath.Join(b.work, rel), 0o750); err != nil {
			notes = append(notes, err.Error())
			continue
		}
		cctx, cancel := context.WithTimeout(ctx, b.timeout)
		ex := run(b.bed.Command(cctx, rel, []string{"consent", "detect", siteURL(s.ID), "--json"}))
		cancel()
		b.mu.Lock()
		b.rssMax = max(b.rssMax, ex.MaxRSS)
		b.mu.Unlock()
		if ex.Exit != 0 {
			notes = append(notes, fmt.Sprintf("%s: detect exited %d: %s", s.ID, ex.Exit, tail(ex.Stderr, 160)))
			continue
		}
		times = append(times, ex.Wall)
	}
	return times, notes
}

// fleetFile writes a sites.yaml of fleetSites entries: every good state
// in list, then repeats of them under new names until there are 50.
func fleetFile(dir string, list []scenarios.Scenario) (string, error) {
	if len(list) == 0 {
		return "", fmt.Errorf("no scenarios for the fleet run")
	}
	var b strings.Builder
	b.WriteString("# Generated by testbed/consent/bench for the fleet measure (PRD 19).\nsites:\n")
	for i := range fleetSites {
		s := list[i%len(list)]
		name, u := s.ID, siteURL(s.ID)
		if i >= len(list) {
			name = fmt.Sprintf("%s-repeat-%d", s.ID, i/len(list))
			u += "?repeat=" + strconv.Itoa(i/len(list))
		}
		fmt.Fprintf(&b, "  - name: %s\n    url: %s\n", name, u)
	}
	path := filepath.Join(dir, "sites.yaml")
	return path, os.WriteFile(path, []byte(b.String()), 0o600)
}

// fleet runs the fleet measure: 50 sites with --parallel 6, every state
// good. It returns the wall time and a note when the run didn't finish
// with a report.
func (b *Bench) fleet(ctx context.Context, list []scenarios.Scenario) (time.Duration, string) {
	for _, s := range list {
		if err := b.bed.SetBroken(s.ID, false); err != nil {
			return 0, err.Error()
		}
	}
	dir := filepath.Join(b.work, "fleet")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return 0, err.Error()
	}
	if _, err := fleetFile(dir, list); err != nil {
		return 0, err.Error()
	}
	cctx, cancel := context.WithTimeout(ctx, 2*targetFleet)
	defer cancel()
	ex := run(b.bed.Command(cctx, "fleet", []string{"consent", "--sites", "sites.yaml", "--parallel", strconv.Itoa(fleetParallel),
		"--json", "-o", "fleet.json", "--fail-on", "none"}))
	b.mu.Lock()
	b.rssMax = max(b.rssMax, ex.MaxRSS)
	b.mu.Unlock()
	if _, err := readEnvelope(filepath.Join(dir, "fleet.json")); err != nil {
		return ex.Wall, fmt.Sprintf("no report (exit %d): %s", ex.Exit, tail(ex.Stderr, 160))
	}
	return ex.Wall, ""
}

// baselineSize reads the v1.1.2 size in bytes from size-v1.1.2.txt:
// its last line that isn't a comment.
func baselineSize(path string) (int64, error) {
	data, err := os.ReadFile(path) //nolint:gosec // the benchmark's own file
	if err != nil {
		return 0, err
	}
	var last string
	for line := range strings.SplitSeq(string(data), "\n") {
		if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "#") {
			last = line
		}
	}
	n, err := strconv.ParseInt(last, 10, 64)
	if err != nil || n <= 0 {
		return 0, fmt.Errorf("%s: want the size in bytes on its last line", path)
	}
	return n, nil
}

// measure builds one Measure: met when ok, missed otherwise, not
// measured when known is false.
func measure(name, value, target string, known, ok bool, note string) Measure {
	m := Measure{Name: name, Value: value, Target: target, Note: note}
	switch {
	case !known:
		m.State = MeasureUnknown
		if m.Value == "" {
			m.Value = "-"
		}
	case ok:
		m.State = MeasureMet
	default:
		m.State = MeasureMissed
	}
	return m
}

// mib is n bytes in MiB with one decimal.
func mib(n int64) string { return fmt.Sprintf("%.1f MiB", float64(n)/(1<<20)) }

// secs is d in seconds with one decimal.
func secs(d time.Duration) string { return fmt.Sprintf("%.1f s", d.Seconds()) }
